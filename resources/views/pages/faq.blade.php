            <h2>What is the difference between CanadaMB and a local website?</h2>
            <p>CanadaMB covers all of Manitoba. Local websites such as BrandonMB focus on their own community.</p>
            <h2>Do I need a different account for each website?</h2>
            <p>No. Your CanadaMB account works across the network. You may be asked to complete secure sign-in when visiting another website.</p>
            <h2>Where will my posts appear?</h2>
            <p>Approved posts for a local community can appear on both CanadaMB and that community's dedicated website, where the relevant module is enabled. Posting on CanadaMB does not mean your post belongs to every city: it is associated with the location you select.</p>
            <h2>How do I browse a different community?</h2>
            <p>Use CanadaMB to explore Manitoba, including communities without a dedicated website. A dedicated community website focuses on its own location.</p>
            <h2>Why is my post not visible yet?</h2>
            <p>Some submissions need moderation before they appear publicly. Check the status in your account.</p>
            <h2>How do I stay safe or get help?</h2>
            <p>Read our <a class="text-link" href="/safety">safety guidance</a>, use available reporting controls, or <a class="text-link" href="/contact">contact support</a>.</p>
